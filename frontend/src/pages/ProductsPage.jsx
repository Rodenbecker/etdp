export default function ProductsPage() {
    const [products, setProducts] = useState(FALLBACK_PRODUCTS);
    const [loading, setLoading] = useState(true);
    const [selectedCategory, setSelectedCategory] = useState('All');
    const [searchQuery, setSearchQuery] = useState('');

    useEffect(() => {
        let mounted = true;
        fetch('/api/Products')
            .then(res => res.json())
            .then(data => {
                if (mounted && data?.success && Array.isArray(data.products) && data.products.length > 0) {
                    setProducts(data.products);
                }
            })
            .catch(() => {
                // Keep fallbacks on network or mock fallback
            })
            .finally(() => {
                if (mounted) setLoading(false);
            });

        return () => { mounted = false; };
    }, []);

    const categories = useMemo(() => {
        const set = new Set();
        products.forEach(p => {
            if (p.category) set.add(p.category);
        });
        return ['All', ...Array.from(set)];
    }, [products]);

    const filteredProducts = useMemo(() => {
        return products.filter(item => {
            const matchesCategory = selectedCategory === 'All' || item.category === selectedCategory;
            const q = searchQuery.toLowerCase().trim();
            const matchesSearch = !q ||
                item.title?.toLowerCase().includes(q) ||
                item.description?.toLowerCase().includes(q) ||
                item.fileName?.toLowerCase().includes(q);
            return matchesCategory && matchesSearch;
        });
    }, [products, selectedCategory, searchQuery]);

    const getFileBadgeClass = (ext) => {
        const e = (ext || '').toLowerCase();
        if (e.includes('pdf')) return 'badge-pdf';
        if (e.includes('xls')) return 'badge-excel';
        if (e.includes('ppt')) return 'badge-powerpoint';
        if (e.includes('mp4') || e.includes('webm')) return 'badge-video';
        return 'badge-generic';
    };

    return (
        <div className="products-page">
            <header className="products-hero">
                <div className="products-hero-content">
                    <span className="products-hero-pill">Accredited Learning Deliverables</span>
                    <h1>Learning Products Delivered</h1>
                    <p>
                        Explore the complete portfolio of publication-ready courseware, curriculum alignment matrices,
                        assessment instruments, logbooks, and multimedia resources generated by the ETDP System.
                    </p>
                </div>
            </header>

            <div className="products-toolbar">
                <div className="products-search-box">
                    <span className="search-icon">🔍</span>
                    <input
                        type="text"
                        placeholder="Search products by title, keyword, or file name..."
                        value={searchQuery}
                        onChange={(e) => setSearchQuery(e.target.value)}
                    />
                    {searchQuery && (
                        <button className="clear-search" onClick={() => setSearchQuery('')}>✕</button>
                    )}
                </div>

                <div className="products-category-pills">
                    {categories.map(cat => (
                        <button
                            key={cat}
                            className={`category-pill ${selectedCategory === cat ? 'active' : ''}`}
                            onClick={() => setSelectedCategory(cat)}
                        >
                            {cat}
                        </button>
                    ))}
                </div>
            </div>

            <div className="products-count-bar">
                <span>Showing <strong>{filteredProducts.length}</strong> of <strong>{products.length}</strong> products</span>
                {loading && <span className="loading-tag">Updating from server...</span>}
            </div>

            <div className="products-grid">
                {filteredProducts.map((item, index) => (
                    <div key={item.fileName || index} className="product-card">
                        <div className="product-card-top">
                            <span className={`file-badge ${getFileBadgeClass(item.extension)}`}>
                                {(item.extension || '').replace('.', '').toUpperCase()}
                            </span>
                            <span className="file-size">{item.fileSizeFormatted}</span>
                        </div>

                        <div className="product-card-body">
                            <span className="product-category-tag">{item.category}</span>
                            <h3 className="product-title">{item.title}</h3>
                            <p className="product-desc">{item.description}</p>
                            <span className="product-filename" title={item.fileName}>
                                📄 {item.fileName}
                            </span>
                        </div>

                        <div className="product-card-actions">
                            <a
                                href={item.downloadUrl}
                                download={item.fileName}
                                className="btn-product-download"
                            >
                                ⬇ Download
                            </a>
                            {(item.extension === '.pdf' || item.extension === '.mp4') && (
                                <a
                                    href={item.downloadUrl}
                                    target="_blank"
                                    rel="noreferrer"
                                    className="btn-product-preview"
                                >
                                    {item.extension === '.mp4' ? '▶ Play' : '👁 View'}
                                </a>
                            )}
                        </div>
                    </div>
                ))}

                {filteredProducts.length === 0 && (
                    <div className="products-empty">
                        <p>No products match your current search or category filter.</p>
                        <button
                            className="btn-reset-filters"
                            onClick={() => { setSelectedCategory('All'); setSearchQuery(''); }}
                        >
                            Reset Filters
                        </button>
                    </div>
                )}
            </div>
        </div>
    );
}
