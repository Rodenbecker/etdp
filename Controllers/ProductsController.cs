        private string? ResolveProductsDirectory()
        {
            var env = Environment.GetEnvironmentVariable("ETDP_PRODUCTS_PATH");
            if (!string.IsNullOrWhiteSpace(env) && Directory.Exists(env))
            {
                return Path.GetFullPath(env.Trim());
            }

            var candidates = new[]
            {
                Path.Combine(EtdpPaths.GetProjectRoot(), "..", "Products"),
                Path.Combine(EtdpPaths.GetProjectRoot(), "Products"),
                Path.Combine(AppContext.BaseDirectory, "Products"),
                Path.Combine(AppContext.BaseDirectory, "..", "Products"),
                @"D:\ETDP\Products"
            };

            foreach (var candidate in candidates)
            {
                try
                {
                    if (Directory.Exists(candidate))
                    {
                        return Path.GetFullPath(candidate);
                    }
                }
                catch
                {
                    // Ignore invalid path probes
                }
            }

            return null;
        }

        [HttpGet]
        public IActionResult GetProducts()
        {
            var dir = ResolveProductsDirectory();
            if (dir == null || !Directory.Exists(dir))
            {
                return Ok(new
                {
                    success = false,
                    message = "Products directory not found on server.",
                    directory = dir,
                    products = Array.Empty<object>()
                });
            }

            var fileEntries = new DirectoryInfo(dir).GetFiles()
                .Where(f => !f.Name.StartsWith(".") && f.Length > 0)
                .OrderBy(f => f.Name)
                .ToList();

            var products = fileEntries.Select(f =>
            {
                ProductMetadata.TryGetValue(f.Name, out var meta);
                var title = !string.IsNullOrWhiteSpace(meta.Title)
                    ? meta.Title
                    : Path.GetFileNameWithoutExtension(f.Name);
                var category = !string.IsNullOrWhiteSpace(meta.Category)
                    ? meta.Category
                    : InferCategory(f.Extension);
                var description = !string.IsNullOrWhiteSpace(meta.Description)
                    ? meta.Description
                    : $"Delivered learning product artifact ({f.Extension.ToUpperInvariant().TrimStart('.')}).";

                return new
                {
                    fileName = f.Name,
                    title,
                    category,
                    description,
                    fileSize = f.Length,
                    fileSizeFormatted = FormatFileSize(f.Length),
                    extension = f.Extension.ToLowerInvariant(),
                    lastModified = f.LastWriteTimeUtc.ToString("o"),
                    downloadUrl = $"/api/Products/download/{Uri.EscapeDataString(f.Name)}"
                };
            }).ToList();

            return Ok(new
            {
                success = true,
                directory = dir,
                totalCount = products.Count,
                products
            });
        }

        [HttpGet("download/{fileName}")]
        public IActionResult DownloadProduct(string fileName)
        {
            if (string.IsNullOrWhiteSpace(fileName))
            {
                return BadRequest("File name is required.");
            }

            var safeName = Path.GetFileName(fileName);
            var dir = ResolveProductsDirectory();
            if (dir == null || !Directory.Exists(dir))
            {
                return NotFound("Products directory is not available.");
            }

            var filePath = Path.Combine(dir, safeName);
            if (!System.IO.File.Exists(filePath))
            {
                return NotFound($"Product file '{safeName}' not found.");
            }

            var contentType = GetMimeType(filePath);
            return PhysicalFile(filePath, contentType, safeName, enableRangeProcessing: true);
        }

        private static string InferCategory(string extension)
        {
            return extension.ToLowerInvariant() switch
            {
                ".pdf" => "Learning Materials",
                ".xlsx" or ".xls" or ".csv" => "Curriculum & Planning",
                ".pptx" or ".ppt" => "Learning Materials",
                ".mp4" or ".webm" => "System Overviews & Media",
                _ => "General Deliverables"
            };
        }

        private static string FormatFileSize(long bytes)
        {
            if (bytes >= 1024 * 1024)
            {
                return $"{(bytes / (1024.0 * 1024.0)):F2} MB";
            }
            if (bytes >= 1024)
            {
                return $"{(bytes / 1024.0):F1} KB";
            }
            return $"{bytes} B";
        }

        private static string GetMimeType(string path)
        {
            var ext = Path.GetExtension(path).ToLowerInvariant();
            return ext switch
            {
                ".pdf" => "application/pdf",
                ".xlsx" => "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                ".xls" => "application/vnd.ms-excel",
                ".pptx" => "application/vnd.openxmlformats-officedocument.presentationml.presentation",
                ".ppt" => "application/vnd.ms-powerpoint",
                ".docx" => "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                ".mp4" => "video/mp4",
                ".webm" => "video/webm",
                ".jpg" or ".jpeg" => "image/jpeg",
                ".png" => "image/png",
                _ => "application/octet-stream"
            };
        }
